import Database from "better-sqlite3";
import {mkdirSync,writeFileSync} from "node:fs";
import {randomBytes,scryptSync} from "node:crypto";
const dir=process.env.QA_DIR||"/home/user/workspace/workflow-qa";
mkdirSync(dir,{recursive:true});
const main=new Database("/home/user/workspace/repair-crm/data.db",{readonly:true});
await main.backup(`${dir}/test.db`);
await main.backup(`${dir}/main-before.db`);
main.close();
const db=new Database(`${dir}/test.db`);
const password=randomBytes(24).toString("base64url");
const salt=randomBytes(16).toString("hex");
const hash=scryptSync(password,salt,64,{N:32768,r:8,p:1,maxmem:64*1024*1024}).toString("hex");
const owner=db.prepare("SELECT id,email FROM staff_accounts WHERE role='owner' LIMIT 1").get() as any;
if(!owner)throw Error("Missing owner in copied database");
db.prepare("UPDATE staff_accounts SET password_hash=?,status='active' WHERE id=?").run(`scrypt$32768$${salt}$${hash}`,owner.id);
writeFileSync(`${dir}/fixture.json`,JSON.stringify({email:owner.email,password}),{mode:0o600});
console.log("Isolated database copied; copy-only owner password configured.");
db.close();
